CREATE SCHEMA IF NOT EXISTS veloscope;

-- ===============================================
-- 0. DROP EXISTING TABLES (WITH CASCADE)
-- ===============================================
DROP TABLE IF EXISTS veloscope.user_favorite_station CASCADE;
DROP TABLE IF EXISTS veloscope."user" CASCADE;
DROP TABLE IF EXISTS veloscope.station_status_hourly CASCADE;
DROP TABLE IF EXISTS veloscope.station_status CASCADE;
DROP TABLE IF EXISTS veloscope.station_physical_capacity CASCADE;
DROP TABLE IF EXISTS veloscope.station_virtual_capacity CASCADE;
DROP TABLE IF EXISTS veloscope.station_information CASCADE;
DROP TABLE IF EXISTS veloscope.vehicle_type CASCADE;
DROP TABLE IF EXISTS veloscope.system_information CASCADE;

-- ===============================================
-- 1. SYSTEM INFORMATION
-- ===============================================
CREATE TABLE veloscope.system_information (
    system_id TEXT PRIMARY KEY,
    language TEXT NOT NULL,
    name TEXT NOT NULL,
    url TEXT,
    start_date DATE,
    phone_number TEXT,
    email TEXT,
    timezone TEXT NOT NULL
);

-- ===============================================
-- 2. STATION INFORMATION
-- ===============================================
CREATE TABLE veloscope.station_information (
    station_id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    short_name TEXT,
    lat DOUBLE PRECISION NOT NULL,
    lon DOUBLE PRECISION NOT NULL,
    address TEXT,
    is_virtual_station BOOLEAN,
    station_area JSONB,
    contact_phone TEXT,
    capacity INT,
    is_charging_station BOOLEAN
);

-- ===============================================
-- 3. STATION STATUS
-- ===============================================
CREATE TABLE veloscope.station_status (
    station_status_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    station_id TEXT NOT NULL REFERENCES veloscope.station_information(station_id) ON DELETE CASCADE ON UPDATE CASCADE,
    num_bikes_available INTEGER NOT NULL,
    num_bikes_disabled INTEGER,
    num_docks_available INTEGER,
    num_docks_disabled INTEGER,
    operational_capacity INTEGER NOT NULL,
    last_reported TIMESTAMPTZ NOT NULL,
    vehicle_types_available JSONB,
    vehicle_docks_available JSONB,
    station_state TEXT NOT NULL
);

-- ===============================================
-- 4. STATION STATUS HOURLY
-- ===============================================
CREATE TABLE veloscope.station_status_hourly (
    station_id TEXT NOT NULL REFERENCES veloscope.station_information(station_id) ON DELETE CASCADE ON UPDATE CASCADE,
    bucket_hour TIMESTAMPTZ NOT NULL,
    sample_count INTEGER NOT NULL,
    avg_operational_capacity REAL NOT NULL,
    avg_num_bikes_available REAL NOT NULL,
    avg_num_docks_available REAL NOT NULL,
    empty_duration_sec INTEGER NOT NULL,
    full_duration_sec INTEGER NOT NULL,
    empty_events_cnt INTEGER NOT NULL,
    full_events_cnt INTEGER NOT NULL,
    reliability_score REAL NOT NULL,
    PRIMARY KEY (station_id, bucket_hour)
);

-- ===============================================
-- 5. USER & FAVORITES
-- ===============================================
CREATE TABLE veloscope."user" (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL UNIQUE,
    password_hashed TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    role TEXT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    access_token TEXT
);

CREATE TABLE veloscope.user_favorite_station (
    user_id INTEGER NOT NULL REFERENCES veloscope."user"(user_id) ON DELETE CASCADE ON UPDATE CASCADE,
    station_id TEXT NOT NULL REFERENCES veloscope.station_information(station_id) ON DELETE CASCADE ON UPDATE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, station_id)
);

-- ===============================================
-- 6. INDEXES
-- ===============================================
CREATE INDEX IF NOT EXISTS idx_station_status_station_reported ON veloscope.station_status (station_id, last_reported DESC);
CREATE INDEX IF NOT EXISTS idx_station_hourly_bucket ON veloscope.station_status_hourly (bucket_hour DESC);
CREATE INDEX IF NOT EXISTS idx_fav_station ON veloscope.user_favorite_station (station_id);
