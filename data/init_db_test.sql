DROP TABLE IF EXISTS vehicle_type CASCADE;
CREATE TABLE vehicle_type(
    vehicle_type_id TEXT PRIMARY KEY,
    form_factor TEXT NOT NULL,
    rider_capacity INT,
    cargo_volume_capacity INT,
    cargo_load_capacity INT,
    propulsion_type TEXT NOT NULL,
    max_range_meters REAL,
    name TEXT,
    return_constraint TEXT
);

DROP TABLE IF EXISTS system_information CASCADE;
CREATE TABLE system_information(
    system_id TEXT PRIMARY KEY,
    language TEXT NOT NULL,
    name TEXT NOT NULL,
    url TEXT,
    start_date DATE,
    phone_number TEXT,
    email TEXT,
    timezone TEXT NOT NULL
);

DROP TABLE IF EXISTS station_information CASCADE;
CREATE TABLE station_information(
    station_id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    short_name TEXT,
    lat DOUBLE PRECISION NOT NULL,
    lon DOUBLE PRECISION NOT NULL,
    address TEXT,
    is_virtual_station BOOLEAN,
    station_area JSONB,
    contact_phone TEXT,
    capacity INT,
    is_charging_station BOOLEAN
);

DROP TABLE IF EXISTS station_virtual_capacity CASCADE;
CREATE TABLE station_virtual_capacity (
    station_id TEXT NOT NULL REFERENCES station_information(station_id) ON DELETE CASCADE ON UPDATE CASCADE,
    vehicle_type_id TEXT NOT NULL REFERENCES vehicle_type(vehicle_type_id) ON DELETE CASCADE ON UPDATE CASCADE,
    capacity INTEGER NOT NULL,
    PRIMARY KEY (station_id, vehicle_type_id)
);

DROP TABLE IF EXISTS station_physical_capacity CASCADE;
CREATE TABLE station_physical_capacity (
    station_id TEXT NOT NULL REFERENCES station_information(station_id) ON DELETE CASCADE ON UPDATE CASCADE,
    vehicle_type_id TEXT NOT NULL REFERENCES vehicle_type(vehicle_type_id) ON DELETE CASCADE ON UPDATE CASCADE,
    dock_count INTEGER NOT NULL,
    PRIMARY KEY (station_id, vehicle_type_id)
);

DROP TABLE IF EXISTS station_status CASCADE;
CREATE TABLE station_status (
    station_status_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    station_id TEXT NOT NULL REFERENCES station_information(station_id) ON DELETE CASCADE ON UPDATE CASCADE,
    num_bikes_available INTEGER NOT NULL,
    num_bikes_disabled INTEGER,
    num_docks_available INTEGER,
    num_docks_disabled INTEGER,
    operational_capacity INTEGER NOT NULL,
    is_installed BOOLEAN NOT NULL,
    is_renting BOOLEAN NOT NULL,
    is_returning BOOLEAN NOT NULL,
    last_reported TIMESTAMPTZ NOT NULL,
    vehicle_types_available JSONB,
    vehicle_docks_available JSONB,
    station_state TEXT NOT NULL
);

DROP TABLE IF EXISTS station_status_hourly CASCADE;
CREATE TABLE station_status_hourly (
    station_id TEXT NOT NULL REFERENCES station_information(station_id) ON DELETE CASCADE ON UPDATE CASCADE,
    bucket_hour TIMESTAMPTZ NOT NULL,
    sample_count INTEGER NOT NULL,
    avg_operational_capacity REAL NOT NULL,
    avg_num_bikes_available REAL NOT NULL,
    avg_num_docks_available REAL NOT NULL,
    empty_duration_sec INTEGER NOT NULL,
    full_duration_sec INTEGER NOT NULL,
    empty_events_cnt INTEGER NOT NULL,
    full_events_cnt INTEGER NOT NULL,
    reliability_score REAL NOT NULL,
    PRIMARY KEY (station_id, bucket_hour)
);

DROP TABLE IF EXISTS "user" CASCADE;
CREATE TABLE "user" (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL UNIQUE,
    password_hashed TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    role TEXT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    access_token TEXT
);

DROP TABLE IF EXISTS user_favorite_station CASCADE;
CREATE TABLE user_favorite_station (
    user_id INTEGER NOT NULL REFERENCES "user"(user_id) ON DELETE CASCADE ON UPDATE CASCADE,
    station_id TEXT NOT NULL REFERENCES station_information(station_id) ON DELETE CASCADE ON UPDATE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, station_id)
);

-- Indexes
CREATE INDEX IF NOT EXISTS idx_station_status_station_reported ON station_status (station_id, last_reported DESC);
CREATE INDEX IF NOT EXISTS idx_station_hourly_bucket ON station_status_hourly (bucket_hour DESC);
CREATE INDEX IF NOT EXISTS idx_fav_station ON user_favorite_station (station_id);

